local locale = GetLocale()
local names = {}
function MapUtils:AddName(loc, english, translated)
	if loc == locale then names[english] = translated end
end

function MapUtils:TransName(english)
	if english == nil then return nil end
	if names[english] ~= nil then return names[english] end
	if not string.find(english, ", ", 1, true) then return english end
	local parts = {}
	for part in string.gmatch(english .. ", ", "(.-), ") do
		tinsert(parts, names[part] or part)
	end

	return table.concat(parts, ", ")
end

